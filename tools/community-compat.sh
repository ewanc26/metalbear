#!/usr/bin/env bash
#
# community-compat.sh — run atproto-smoke against a throwaway local MetalBear.
#
# Issue #249. This is the shared body of the nightly advisory workflow: it
# builds no code and installs no suites, but boots `build/metalbear` in
# scripts/setup.sh --local semantics (loopback, did:key accounts, no PLC
# writes), provisions two accounts, writes a suite config with CI-only
# passwords and runs the suite's single-mode browser checks.
#
# Required environment:
#   SUITE_DIR   checkout of aliceisjustplaying/atproto-smoke (pinned by caller)
# Optional:
#   BUILD_DIR   directory containing the `metalbear` binary (default: build)
#   OUTPUT_DIR  where summary.json, logs and artifacts are written
#   PORT        loopback port (default: 2583)
#
# Passwords are generated at runtime and never printed. Nothing here is a
# required status check: divergences are triaged in docs/conformance.md.
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
suite_dir=${SUITE_DIR:?SUITE_DIR is required}
build_dir=${BUILD_DIR:-$repo_root/build}
output_dir=${OUTPUT_DIR:-$repo_root/build/community-compat}
port=${PORT:-2583}
binary="$build_dir/metalbear"

if [ ! -x "$binary" ]; then
	printf 'community-compat: no binary at %s; build first\n' "$binary" >&2
	exit 2
fi
if [ ! -f "$suite_dir/bin/atproto-smoke.ts" ]; then
	printf 'community-compat: no suite at %s\n' "$suite_dir" >&2
	exit 2
fi

mkdir -p "$output_dir"
work=$(mktemp -d "$output_dir/work.XXXXXX")
server_pid=""

cleanup() {
	if [ -n "$server_pid" ]; then
		kill "$server_pid" 2>/dev/null || true
		wait "$server_pid" 2>/dev/null || true
	fi
	rm -rf "$work"
}
trap cleanup EXIT

password_a=$(openssl rand -hex 16)
password_b=$(openssl rand -hex 16)
admin_password=$(openssl rand -hex 16)
handle_a="smoke-a.localhost"
handle_b="smoke-b.localhost"

cat >"$work/metalbear.yaml" <<EOF
# Generated by tools/community-compat.sh. Throwaway, loopback only.
server:
  listen: "127.0.0.1"
  port: ${port}
  threads: 2
  data: "${work}/data"
  service_did: "did:web:localhost%3A${port}"
  public_url: "http://localhost:${port}"
  user_domain: ".localhost"

operator:
  name: "MetalBear community compatibility"
  description: "Throwaway local instance for atproto-smoke"
  development: true

# No identity.plc_url: createAccount mints did:key, so no PLC write escapes.
identity:
  did_cache_ttl_seconds: 300
  did_cache_entries: 64

accounts:
  admin_password: "${admin_password}"
  invite_required: false

limits:
  rate_limit: 3000
  rate_limit_window_seconds: 60

firehose:
  crawl_notify_seconds: 1200
  ping_seconds: 20

appview:
  url: "https://api.bsky.app"
  did: "did:web:api.bsky.app"
EOF

printf 'community-compat: starting MetalBear on 127.0.0.1:%s\n' "$port"
METALBEAR_CONFIG="$work/metalbear.yaml" "$binary" >"$work/server.log" 2>&1 &
server_pid=$!

healthy=0
for _ in $(seq 1 60); do
	if curl -fsS "http://127.0.0.1:${port}/xrpc/_health" >/dev/null 2>&1; then
		healthy=1
		break
	fi
	if ! kill -0 "$server_pid" 2>/dev/null; then
		break
	fi
	sleep 0.5
done
if [ "$healthy" -ne 1 ]; then
	printf 'community-compat: server did not become healthy; log tail:\n' >&2
	tail -30 "$work/server.log" >&2 || true
	exit 1
fi

create_account() {
	local handle=$1 password=$2 payload code
	payload=$(HANDLE="$handle" PASSWORD="$password" python3 -c '
import json, os
print(json.dumps({
    "handle": os.environ["HANDLE"],
    "password": os.environ["PASSWORD"],
    "email": os.environ["HANDLE"] + "@localhost",
}))
')
	code=$(curl -sS -o "$work/create-$handle.json" -w '%{http_code}' \
		-X POST -H 'Content-Type: application/json' --data "$payload" \
		"http://127.0.0.1:${port}/xrpc/com.atproto.server.createAccount")
	if [ "$code" != 200 ]; then
		printf 'community-compat: createAccount for %s returned %s\n' \
			"$handle" "$code" >&2
		cat "$work/create-$handle.json" >&2 || true
		return 1
	fi
}
create_account "$handle_a" "$password_a"
create_account "$handle_b" "$password_b"

SUITE_CONFIG="$work/suite.json" \
SUITE_OUTPUT="$work/suite-artifacts" \
HANDLE_A="$handle_a" HANDLE_B="$handle_b" \
PASSWORD_A="$password_a" PASSWORD_B="$password_b" \
PORT="$port" python3 - <<'PY'
import json, os

config = {
    "pdsUrl": "http://localhost:%s" % os.environ["PORT"],
    "pdsHost": "localhost:%s" % os.environ["PORT"],
    "artifactsDir": os.environ["SUITE_OUTPUT"],
    "appUrl": "https://bsky.app",
    "publicApiUrl": "https://public.api.bsky.app",
    "publicChecks": False,
    "strictErrors": False,
    "headless": True,
    "stepTimeoutMs": 30000,
    "publicCheckTimeoutMs": 10000,
    "targetHandle": os.environ["HANDLE_A"],
    "account": {
        "handle": os.environ["HANDLE_A"],
        "password": os.environ["PASSWORD_A"],
    },
}
with open(os.environ["SUITE_CONFIG"], "w", encoding="utf-8") as handle:
    json.dump(config, handle, indent=2)
    handle.write("\n")
PY

printf 'community-compat: running atproto-smoke single mode\n'
set +e
(
	cd "$suite_dir"
	bunx tsx bin/atproto-smoke.ts run-single \
		--config "$work/suite.json" --json-only \
		>"$output_dir/summary.json" 2>"$output_dir/suite.log"
)
status=$?
set -e

if [ -d "$work/suite-artifacts" ]; then
	rm -rf "$output_dir/artifacts"
	cp -R "$work/suite-artifacts" "$output_dir/artifacts"
fi
cp "$work/server.log" "$output_dir/server.log"

printf 'community-compat: suite exit %s; results in %s\n' \
	"$status" "$output_dir"
exit "$status"
