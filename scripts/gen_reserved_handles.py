#!/usr/bin/env python3
"""gen_reserved_handles.py -- regenerate src/handle/reserved_data.c.

Extracts the three reserved-label arrays from the reference PDS's
packages/pds/src/handle/reserved.ts and emits them as a sorted C string
table. Extraction is mechanical rather than a hand transcription: the list
is over a thousand entries, sourced from bluesky-social/atproto (MIT /
Apache-2.0) and, for commonlyReserved, from a radwebhosting knowledgebase
list as noted in the reference source.

Usage:
    python3 scripts/gen_reserved_handles.py <path-to-reserved.ts>

Writes src/handle/reserved_data.c relative to the repo root (this script's
parent directory's parent).
"""

import re
import sys
from pathlib import Path

ARRAYS = ("atpSpecific", "commonlyReserved", "famousAccounts")


def extract_words(ts_source: str, name: str) -> list[str]:
    marker = f"const {name} = ["
    if marker not in ts_source:
        raise ValueError(f"array {name} not found in reference source")
    body = ts_source.split(marker, 1)[1].split("]", 1)[0]
    return re.findall(r"'([^']+)'", body)


def c_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render_c(words: list[str]) -> str:
    lines = [
        "/**",
        " * reserved_data.c -- generated reserved-handle labels.",
        " *",
        " * Generated by scripts/gen_reserved_handles.py from the reference PDS's",
        " * packages/pds/src/handle/reserved.ts (bluesky-social/atproto,",
        " * MIT/Apache-2.0). commonlyReserved is itself sourced from a public",
        " * list of banned subdomain prefixes, as credited in that file. Do not",
        " * hand-edit; update the reference and regenerate.",
        " */",
        "",
        '#include "reserved_internal.h"',
        "",
        "const char *const metalbear_reserved_labels[] = {",
    ]
    for word in words:
        lines.append(f'    "{c_escape(word)}",')
    lines.extend(
        [
            "};",
            "",
            "const size_t metalbear_reserved_label_count =",
            f"    sizeof(metalbear_reserved_labels) / sizeof(metalbear_reserved_labels[0]);",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen_reserved_handles.py <path-to-reserved.ts>")
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    words = sorted({word for name in ARRAYS for word in extract_words(source, name)})
    if not words:
        raise ValueError("no reserved labels extracted")
    root = Path(__file__).resolve().parent.parent
    out = root / "src" / "handle" / "reserved_data.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_c(words), encoding="utf-8")
    print(f"wrote {out} ({len(words)} labels)")


if __name__ == "__main__":
    main()
